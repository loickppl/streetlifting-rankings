function flagEmoji(iso) {
  // Flag images (emoji flags don't render on Windows); alt shows the code.
  if (!iso || iso.length !== 2) return "";
  const cc = iso.toLowerCase();
  return `<img class="flag-img" src="https://flagcdn.com/w20/${cc}.png" srcset="https://flagcdn.com/w40/${cc}.png 2x" alt="${iso.toUpperCase()}" loading="lazy" width="20" height="15">`;
}
function fmt(v, digits = 2) {
  if (v == null) return "—";
  return Number(v).toLocaleString(state.lang === "fr" ? "fr-FR" : "en-US",
    { minimumFractionDigits: 0, maximumFractionDigits: digits });
}
function fmtDate(d) {
  if (!d || !/^\d{4}-\d{2}-\d{2}$/.test(d)) return d || "—";
  return new Date(d + "T00:00:00").toLocaleDateString(state.lang === "fr" ? "fr-FR" : "en-US",
    { year: "numeric", month: "short", day: "numeric" });
}
function esc(s) {
  return String(s ?? "").replace(/[&<>"']/g, c => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c]));
}
function classSort(a, b) {
  // lightest first: -66 … -101, then +101 last ("all"/Open first)
  const n = (c) => c === "all" ? -1 : parseFloat(c.slice(1)) + (c.startsWith("+") ? 0.5 : 0);
  return n(a) - n(b);
}

/* ── i18n ─────────────────────────────────────────────────── */
function applyI18n() {
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const v = t()[el.dataset.i18n];
    if (typeof v === "string") el.innerHTML = v;
  });
  document.querySelectorAll("[data-i18n-ph]").forEach(el => {
    const v = t()[el.dataset.i18nPh];
    if (v) el.placeholder = v;
  });
  $("#lang-toggle").textContent = state.lang === "fr" ? "EN" : "FR";
  document.documentElement.lang = state.lang;
  renderHeroStats();
  if (state.meta) {
    $("#footer-updated").textContent =
      `${t().updated} ${fmtDate(state.meta.generated_at?.slice(0, 10))}`;
  }
}

function renderHeroStats() {
  if (!state.meta) return;
  const s = state.meta.sources;
  const stats = [
    [state.athletes.length, t().stat_athletes],
    [state.performances.length, t().stat_perfs],
    [s.finalrep?.records ?? 0, t().stat_records],
    [fmtDate(state.meta.generated_at?.slice(0, 10)), t().stat_updated],
  ];
  $("#hero-stats").innerHTML = stats.map(([v, l]) =>
    `<div class="hstat"><span class="v">${esc(String(v))}</span><span class="l">${esc(l)}</span></div>`).join("");
}

/* ── data ─────────────────────────────────────────────────── */
async function loadData() {
  const [perfs, athletes, records, meta] = await Promise.all(
    ["performances", "athletes", "records", "meta"].map(n =>
      fetch(`data/${n}.json`).then(r => r.ok ? r.json() : Promise.reject(new Error(n)))));
  state.performances = perfs;
  state.athletes = athletes;
  state.records = records;
  state.meta = meta;
}

/* ── filter widgets ───────────────────────────────────────── */
function classesFor(gender) {
  const set = new Set(state.performances
    .filter(p => p.gender === gender && p.class).map(p => p.class));
  return [...set].sort(classSort);
}
// current official weight classes; legacy ones collapse behind a "+N" chip
const MAIN_CLASSES = {
  male: ["-66kg", "-73kg", "-80kg", "-87kg", "-94kg", "-101kg", "+101kg"],
  female: ["-52kg", "-57kg", "-63kg", "-70kg", "+70kg"],
};
function refreshClassChips() {
  const wrap = $("#f-class");
  const classes = classesFor(state.gender);
  if (!classes.includes(state.klass)) state.klass = "";
  const main = (MAIN_CLASSES[state.gender] || []).filter(c => classes.includes(c));
  const extra = classes.filter(c => !main.includes(c));
  if (extra.includes(state.klass)) state.showAllClasses = true;
  const chip = (c) =>
    `<button class="chip ${state.klass === c ? "active" : ""}" data-value="${esc(c)}">${esc(c)}</button>`;
  wrap.innerHTML =
    `<button class="chip ${state.klass === "" ? "active" : ""}" data-value="">${t().all_classes}</button>` +
    main.map(chip).join("") +
    (extra.length
      ? (state.showAllClasses
          ? extra.map(chip).join("") + `<button class="chip chip-more" data-more="1">−</button>`
          : `<button class="chip chip-more" data-more="1">+${extra.length}</button>`)
      : "");
}
function refreshStyleOptions() {
  const sel = $("#f-style");
  const prev = sel.value;
  const styles = [...new Set(state.performances.map(p => p.style).filter(Boolean))].sort();
  sel.innerHTML = `<option value="">${t().all_f}</option>` +
    styles.map(s => `<option value="${esc(s)}">${esc(s)}</option>`).join("");
  if ([...sel.options].some(o => o.value === prev)) sel.value = prev;
}

/* ── rankings ─────────────────────────────────────────────── */
function rankingRows() {
  const style = $("#f-style").value;
  const q = $("#f-search").value.trim().toLowerCase();
  const bestOnly = $("#f-best").checked;
  const { gender, metric, klass } = state;

  let rows = state.performances.filter(p =>
    p.gender === gender && p[metric] != null &&
    (!klass || p.class === klass) &&
    (!style || p.style === style) &&
    (!q || `${p.athlete} ${p.country} ${p.competition}`.toLowerCase().includes(q)));

  rows.sort((a, b) => b[metric] - a[metric]);
  if (bestOnly) {
    const seen = new Set();
    rows = rows.filter(r => !seen.has(r.athlete_id) && seen.add(r.athlete_id));
  }
  return rows;
}

function renderPodium(rows) {
  const { metric } = state;
  const unit = metric === "ris" ? "" : "kg";
  $("#podium").innerHTML = rows.slice(0, 3).map((p, i) => `
    <div class="podium-card p${i + 1}" data-athlete="${esc(p.athlete_id)}">
      <div class="pos">${i + 1}</div>
      <span class="medal">#${i + 1}</span>
      <div class="who"><span>${flagEmoji(p.country)}</span> ${esc(p.athlete)}</div>
      <div class="meta">${esc(p.class ?? "")}${p.bodyweight ? ` · ${fmt(p.bodyweight)} kg` : ""}</div>
      <div class="value">${fmt(p[metric])}<span class="unit">${unit}</span></div>
      <div class="where">${esc(p.competition ?? "")} — ${fmtDate(p.date)}</div>
    </div>`).join("");
}

function renderRankings() {
  const rows = rankingRows();
  const top = parseInt($("#f-top").value, 10);
  const shown = top > 0 ? rows.slice(0, top) : rows;
  const { gender, metric, klass } = state;

  renderPodium(shown);

  $("#rankings-title").textContent = t().ranking_title(
    gender === "male" ? t().men : t().women,
    klass || t().all_classes,
    t().metric_names[metric]);
  $("#rankings-count").textContent = `${shown.length} / ${rows.length} ${t().results}`;

  const metricKey = { muscle_up: "col_mu", pull_up: "col_pu", dip: "col_dip", squat: "col_sq", total: "col_total", ris: "col_ris" }[metric];
  const cols = [
    ["col_rank", ""], ["col_athlete", ""],
    ["col_mu", "num"], ["col_pu", "num"], ["col_dip", "num"], ["col_sq", "num"],
    ["col_total", "num"], ["col_ris", "num"], ["col_comp", ""],
  ];
  const thead = `<thead><tr>${cols.map(([k, cls]) =>
    `<th class="${cls} ${k === metricKey ? "sorted" : ""}">${t()[k]}</th>`).join("")}</tr></thead>`;

  const maxVal = shown.length ? shown[0][metric] : 1;
  const valueCell = (p, m) => {
    if (m !== metric)
      return `<td class="num mv">${fmt(p[m])}</td>`;
    const pct = Math.max(6, Math.round((p[m] / maxVal) * 100));
    return `<td class="num metric-cell">
      <div class="metric-val">${fmt(p[m])}</div>
      <div class="metric-bar" style="width:${pct * 0.62}px"></div>
    </td>`;
  };
  const subLine = (p) => {
    const rest = [p.bodyweight ? `${fmt(p.bodyweight)} kg` : null, p.style]
      .filter(Boolean).map(esc).join(" · ");
    const cls = p.class ? `<b>${esc(p.class)}</b>` : "";
    return cls + (cls && rest ? " · " : "") + rest;
  };

  const body = shown.length === 0
    ? `<tbody><tr><td colspan="9" class="empty-row">${t().no_data}</td></tr></tbody>`
    : `<tbody>${shown.map((p, i) => `<tr class="${i < 3 ? `top3 t${i + 1}` : ""}">
        <td class="rank-cell">${i + 1}</td>
        <td class="id-cell">
          <div class="id-name"><span class="flag">${flagEmoji(p.country)}</span><span class="athlete-link" data-athlete="${esc(p.athlete_id)}">${esc(p.athlete)}</span></div>
          <div class="id-sub">${subLine(p)}</div>
        </td>
        ${valueCell(p, "muscle_up")}${valueCell(p, "pull_up")}${valueCell(p, "dip")}${valueCell(p, "squat")}
        ${valueCell(p, "total")}${valueCell(p, "ris")}
        <td class="comp-cell">
          <div class="comp-name" title="${esc(p.competition ?? "")}">${esc(p.competition ?? "—")}</div>
          <div class="comp-date">${fmtDate(p.date)}</div>
        </td>
      </tr>`).join("")}</tbody>`;

  $("#rankings-table").innerHTML = thead + body;
}

/* ── records ──────────────────────────────────────────────── */
function renderRecords() {
  const grid = $("#records-grid");
  const mn = t().metric_names;
  const gender = state.rGender;

  const card = (title, tag, rowsHtml) => `
    <div class="record-card">
      <div class="record-card-head"><h3>${title}</h3><span class="tag">${tag}</span></div>
      <div class="record-rows">${rowsHtml}</div>
    </div>`;

  if (state.rSource === "finalrep") {
    const recs = state.records.finalrep.filter(r => r.gender === gender);
    const byClass = {};
    recs.forEach(r => (byClass[r.class] ??= []).push(r));
    grid.innerHTML = Object.keys(byClass).sort(classSort).map(c =>
      card(esc(c), "WR",
        ["total", "muscle_up", "pull_up", "dip", "squat"].map(m => {
          const r = byClass[c].find(x => x.movement === m);
          if (!r) return "";
          const ig = r.instagram
            ? `<a class="ig" href="https://instagram.com/${esc(r.instagram.slice(1))}" target="_blank" rel="noopener">${esc(r.instagram)}</a>` : "";
          return `<div class="record-row">
            <span class="record-move">${mn[m]}</span>
            <span class="record-holder">${esc(r.athlete)}${ig}</span>
            <span class="record-value">${fmt(r.weight_kg)}<small>kg</small></span>
          </div>`;
        }).join(""))
    ).join("") || `<p class="empty-row">${t().no_data}</p>`;
  } else {
    const recs = state.records.computed_osl.filter(r => r.gender === gender);
    const byClass = {};
    recs.forEach(r => (byClass[r.class] ??= []).push(r));
    grid.innerHTML = Object.keys(byClass).sort(classSort).map(c =>
      card(c === "all" ? t().all_classes : esc(c), "OSL",
        ["total", "ris", "muscle_up", "pull_up", "dip", "squat"].map(m => {
          const r = byClass[c].find(x => x.movement === m);
          if (!r) return "";
          return `<div class="record-row">
            <span class="record-move">${mn[m]}</span>
            <span class="record-holder"><span class="athlete-link" data-athlete="${esc(r.athlete_id)}">${flagEmoji(r.country)} ${esc(r.athlete)}</span></span>
            <span class="record-value">${fmt(r.value)}<small>${m === "ris" ? "" : "kg"}</small></span>
          </div>`;
        }).join(""))
    ).join("") || `<p class="empty-row">${t().no_data}</p>`;
  }
}

/* ── athletes ─────────────────────────────────────────────── */
function renderAthletes() {
  const q = $("#a-search").value.trim().toLowerCase();
  let rows = state.athletes.filter(a =>
    (!state.aGender || a.gender === state.aGender) &&
    (!q || `${a.name} ${a.country}`.toLowerCase().includes(q)));

  const key = state.sort.key;
  const get = (a) => key === "name" ? (a.name || "") : key === "n" ? a.n_competitions :
    key === "ris" ? (a.best_ris ?? -1) : (a.best?.[key] ?? -1);
  rows.sort((a, b) => {
    const va = get(a), vb = get(b);
    return (typeof va === "string" ? va.localeCompare(vb) : va - vb) * state.sort.dir;
  });

  const headers = [
    ["name", "col_athlete", ""], ["muscle_up", "col_mu", "num"],
    ["pull_up", "col_pu", "num"], ["dip", "col_dip", "num"], ["squat", "col_sq", "num"],
    ["total", "col_total", "num"], ["ris", "col_best_ris", "num"],
  ];
  $("#athletes-table").innerHTML =
    `<thead><tr>${headers.map(([k, label, cls]) =>
      `<th data-sort="${k}" class="${cls} ${state.sort.key === k ? "sorted" : ""}">${t()[label]}</th>`).join("")}</tr></thead>` +
    `<tbody>${rows.map(a => `<tr>
      <td class="id-cell">
        <div class="id-name"><span class="flag">${flagEmoji(a.country)}</span><span class="athlete-link" data-athlete="${esc(a.id)}">${esc(a.name)}</span></div>
        <div class="id-sub">${a.n_competitions} ${compWord(a.n_competitions)}</div>
      </td>
      <td class="num mv">${fmt(a.best?.muscle_up)}</td>
      <td class="num mv">${fmt(a.best?.pull_up)}</td>
      <td class="num mv">${fmt(a.best?.dip)}</td>
      <td class="num mv">${fmt(a.best?.squat)}</td>
      <td class="num strong-val">${fmt(a.best?.total)}</td>
      <td class="num mv">${fmt(a.best_ris)}</td>
    </tr>`).join("")}</tbody>`;
}

