(async function init() {
  try {
    state.lang = localStorage.getItem("sl-lang") ||
      ((navigator.language || "fr").toLowerCase().startsWith("fr") ? "fr" : "en");
  } catch {}
  bind();
  applyI18n();
  const tab = location.hash.slice(1);
  if (["records", "athletes"].includes(tab)) setTab(tab, false);
  try {
    await loadData();
  } catch (err) {
    $("#rankings-table").innerHTML =
      `<tbody><tr><td class="empty-row">Data not available (${esc(err.message || err)})</td></tr></tbody>`;
    return;
  }
  applyI18n();
  refreshClassChips();
  refreshStyleOptions();
  renderRankings();
  renderRecords();
  renderAthletes();
})();
