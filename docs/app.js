/* ---------- events ---------- */
function bind() {
  $("#tabs").addEventListener("click", (e) => {
    const btn = e.target.closest(".tab");
    if (!btn) return;
    document.querySelectorAll(".tab").forEach(b => b.classList.toggle("active", b === btn));
    document.querySelectorAll(".panel").forEach(p => p.classList.toggle("active", p.id === `panel-${btn.dataset.tab}`));
  });

  $("#lang-toggle").addEventListener("click", () => {
    state.lang = state.lang === "fr" ? "en" : "fr";
    try { localStorage.setItem("sl-lang", state.lang); } catch {}
    applyI18n(); refreshClassOptions(); refreshStyleOptions();
    renderRankings(); renderRecords(); renderAthletes();
  });

  $("#f-gender").addEventListener("change", () => { refreshClassOptions(); renderRankings(); });
  ["#f-metric", "#f-class", "#f-style", "#f-top", "#f-best"].forEach(s =>
    $(s).addEventListener("change", renderRankings));
  $("#f-search").addEventListener("input", renderRankings);

  ["#r-source", "#r-gender"].forEach(s => $(s).addEventListener("change", renderRecords));

  $("#a-search").addEventListener("input", renderAthletes);
  $("#a-gender").addEventListener("change", renderAthletes);
  $("#athletes-table").addEventListener("click", (e) => {
    const th = e.target.closest("th[data-sort]");
    if (!th) return;
    const k = th.dataset.sort;
    state.sort = { key: k, dir: state.sort.key === k ? -state.sort.dir : (k === "name" ? 1 : -1) };
    renderAthletes();
  });

  document.body.addEventListener("click", (e) => {
    const link = e.target.closest("[data-athlete]");
    if (link) openAthlete(link.dataset.athlete);
  });
  $("#modal-close").addEventListener("click", () => $("#modal").classList.add("hidden"));
  $("#modal").addEventListener("click", (e) => { if (e.target === $("#modal")) $("#modal").classList.add("hidden"); });
  document.addEventListener("keydown", (e) => { if (e.key === "Escape") $("#modal").classList.add("hidden"); });
}

/* ---------- init ---------- */
(async function init() {
  try { state.lang = localStorage.getItem("sl-lang") || ((navigator.language || "fr").toLowerCase().startsWith("fr") ? "fr" : "en"); } catch {}
  bind();
  applyI18n();
  try {
    await loadData();
  } catch (err) {
    $("#rankings-table").innerHTML = `<tbody><tr><td class="loading">Data not available (${esc(err)})</td></tr></tbody>`;
    return;
  }
  applyI18n();
  refreshClassOptions();
  refreshStyleOptions();
  renderRankings();
  renderRecords();
  renderAthletes();
})();
