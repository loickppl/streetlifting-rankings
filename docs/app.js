/* ── events ───────────────────────────────────────────────── */
function setTab(tab, pushHash) {
  document.querySelectorAll(".nav-link").forEach(b => b.classList.toggle("active", b.dataset.tab === tab));
  document.querySelectorAll(".panel").forEach(p => p.classList.toggle("active", p.id === `panel-${tab}`));
  if (pushHash) history.replaceState(null, "", tab === "rankings" ? location.pathname : `#${tab}`);
}

function segBind(sel, onChange) {
  $(sel).addEventListener("click", (e) => {
    const btn = e.target.closest(".seg-btn");
    if (!btn) return;
    $(sel).querySelectorAll(".seg-btn").forEach(b => b.classList.toggle("active", b === btn));
    onChange(btn.dataset.value);
  });
}

function bind() {
  $("#tabs").addEventListener("click", (e) => {
    const btn = e.target.closest(".nav-link");
    if (!btn) return;
    setTab(btn.dataset.tab, true);
  });
  window.addEventListener("hashchange", () => {
    const tab = location.hash.slice(1);
    if (["rankings", "records", "athletes"].includes(tab)) setTab(tab, false);
  });
  $("#brand").addEventListener("click", (e) => e.preventDefault());

  $("#lang-toggle").addEventListener("click", () => {
    state.lang = state.lang === "fr" ? "en" : "fr";
    try { localStorage.setItem("sl-lang", state.lang); } catch {}
    applyI18n(); refreshClassChips(); refreshStyleOptions();
    renderRankings(); renderRecords(); renderAthletes();
  });

  segBind("#f-gender", (v) => { state.gender = v; refreshClassChips(); renderRankings(); });
  $("#f-metric").addEventListener("click", (e) => {
    const btn = e.target.closest(".pill");
    if (!btn) return;
    state.metric = btn.dataset.value;
    $("#f-metric").querySelectorAll(".pill").forEach(b => b.classList.toggle("active", b === btn));
    renderRankings();
  });
  $("#f-class").addEventListener("click", (e) => {
    const btn = e.target.closest(".chip");
    if (!btn) return;
    if (btn.dataset.more) {
      state.showAllClasses = !state.showAllClasses;
      refreshClassChips();
      return;
    }
    state.klass = btn.dataset.value;
    $("#f-class").querySelectorAll(".chip").forEach(b => b.classList.toggle("active", b === btn));
    renderRankings();
  });
  ["#f-style", "#f-top", "#f-best"].forEach(s => $(s).addEventListener("change", renderRankings));
  $("#f-search").addEventListener("input", renderRankings);

  segBind("#r-gender", (v) => { state.rGender = v; renderRecords(); });
  segBind("#r-source", (v) => { state.rSource = v; renderRecords(); });

  segBind("#a-gender", (v) => { state.aGender = v; renderAthletes(); });
  $("#a-search").addEventListener("input", renderAthletes);
  $("#athletes-table").addEventListener("click", (e) => {
    const th = e.target.closest("th[data-sort]");
    if (!th) return;
    const k = th.dataset.sort;
    state.sort = { key: k, dir: state.sort.key === k ? -state.sort.dir : (k === "name" ? 1 : -1) };
    renderAthletes();
  });

  document.body.addEventListener("click", (e) => {
    const link = e.target.closest("[data-athlete]");
    if (link) openAthlete(link.dataset.athlete);
  });
  $("#modal-close").addEventListener("click", () => $("#modal").classList.add("hidden"));
  $("#modal").addEventListener("click", (e) => { if (e.target === $("#modal")) $("#modal").classList.add("hidden"); });
  document.addEventListener("keydown", (e) => { if (e.key === "Escape") $("#modal").classList.add("hidden"); });
}

