const state = {
  lang: localStorage.getItem("sl-lang") || (navigator.language || "fr").startsWith("fr") ? (localStorage.getItem("sl-lang") || "fr") : (localStorage.getItem("sl-lang") || "en"),
  performances: [],
  athletes: [],
  records: { finalrep: [], computed_osl: [] },
  meta: null,
  sort: { key: null, dir: -1 },
};

const $ = (sel) => document.querySelector(sel);
const t = () => I18N[state.lang];

function flagEmoji(iso) {
  if (!iso || iso.length !== 2) return "";
  return String.fromCodePoint(...[...iso.toUpperCase()].map(c => 0x1f1e6 + c.charCodeAt(0) - 65));
}
function fmt(v, digits = 2) {
  if (v == null) return "—";
  return Number(v).toLocaleString(state.lang === "fr" ? "fr-FR" : "en-US",
    { minimumFractionDigits: 0, maximumFractionDigits: digits });
}
function fmtDate(d) {
  if (!d || !/^\d{4}-\d{2}-\d{2}$/.test(d)) return d || "—";
  return new Date(d + "T00:00:00").toLocaleDateString(state.lang === "fr" ? "fr-FR" : "en-US",
    { year: "numeric", month: "short", day: "numeric" });
}
function esc(s) {
  return String(s ?? "").replace(/[&<>"']/g, c => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c]));
}

/* ---------- i18n ---------- */
function applyI18n() {
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const v = t()[el.dataset.i18n];
    if (typeof v === "string") el.innerHTML = v;
  });
  document.querySelectorAll("[data-i18n-ph]").forEach(el => {
    const v = t()[el.dataset.i18nPh];
    if (v) el.placeholder = v;
  });
  $("#lang-toggle").textContent = state.lang === "fr" ? "EN" : "FR";
  document.documentElement.lang = state.lang;
  if (state.meta) {
    const d = state.meta.generated_at?.slice(0, 10);
    $("#last-updated").textContent = `${t().updated} ${fmtDate(d)}`;
  }
}

/* ---------- data ---------- */
async function loadData() {
  const [perfs, athletes, records, meta] = await Promise.all(
    ["performances", "athletes", "records", "meta"].map(n =>
      fetch(`data/${n}.json`).then(r => r.ok ? r.json() : Promise.reject(n))));
  state.performances = perfs;
  state.athletes = athletes;
  state.records = records;
  state.meta = meta;
}

/* ---------- filters ---------- */
function classesFor(gender) {
  const set = new Set(state.performances.filter(p => p.gender === gender && p.class).map(p => p.class));
  return [...set].sort((a, b) => parseFloat(a.replace("+", "9")) - parseFloat(b.replace("+", "9")));
}
function stylesAll() {
  return [...new Set(state.performances.map(p => p.style).filter(Boolean))].sort();
}
function refreshClassOptions() {
  const gender = $("#f-gender").value;
  const sel = $("#f-class");
  const prev = sel.value;
  sel.innerHTML = `<option value="">${t().all_classes}</option>` +
    classesFor(gender).map(c => `<option value="${esc(c)}">${esc(c)}</option>`).join("");
  if ([...sel.options].some(o => o.value === prev)) sel.value = prev;
}
function refreshStyleOptions() {
  const sel = $("#f-style");
  const prev = sel.value;
  sel.innerHTML = `<option value="">${t().all_f}</option>` +
    stylesAll().map(s => `<option value="${esc(s)}">${esc(s)}</option>`).join("");
  if ([...sel.options].some(o => o.value === prev)) sel.value = prev;
}

/* ---------- rankings ---------- */
function renderRankings() {
  const gender = $("#f-gender").value;
  const metric = $("#f-metric").value;
  const klass = $("#f-class").value;
  const style = $("#f-style").value;
  const top = parseInt($("#f-top").value, 10);
  const q = $("#f-search").value.trim().toLowerCase();
  const bestOnly = $("#f-best").checked;

  let rows = state.performances.filter(p =>
    p.gender === gender && p[metric] != null &&
    (!klass || p.class === klass) &&
    (!style || p.style === style) &&
    (!q || `${p.athlete} ${p.country} ${p.competition}`.toLowerCase().includes(q)));

  rows.sort((a, b) => b[metric] - a[metric]);
  if (bestOnly) {
    const seen = new Set();
    rows = rows.filter(r => !seen.has(r.athlete_id) && seen.add(r.athlete_id));
  }
  const total = rows.length;
  if (top > 0) rows = rows.slice(0, top);

  $("#rankings-title").textContent = t().ranking_title(
    top > 0 ? Math.min(top, total) : total,
    gender === "male" ? t().men : t().women,
    klass);

  const cols = [
    ["col_rank", null], ["col_athlete", null], ["col_class", null], ["col_bw", "num"],
    ["col_style", null], ["col_mu", "num"], ["col_pu", "num"], ["col_dip", "num"],
    ["col_sq", "num"], ["col_total", "num"], ["col_ris", "num"], ["col_comp", null], ["col_date", null],
  ];
  const metricCol = { muscle_up: "col_mu", pull_up: "col_pu", dip: "col_dip", squat: "col_sq", total: "col_total", ris: "col_ris" }[metric];

  const thead = `<thead><tr>${cols.map(([k, cls]) =>
    `<th class="${cls || ""} ${k === metricCol ? "sorted" : ""}">${t()[k]}</th>`).join("")}</tr></thead>`;

  const body = rows.length === 0 ? `<tbody><tr><td colspan="13" class="loading">${t().no_data}</td></tr></tbody>` :
    `<tbody>${rows.map((p, i) => `<tr>
      <td class="rank rank-${i + 1}">${i + 1}</td>
      <td><span class="athlete-link" data-athlete="${esc(p.athlete_id)}"><span class="flag">${flagEmoji(p.country)}</span>${esc(p.athlete)}</span></td>
      <td>${esc(p.class ?? "—")}</td>
      <td class="num">${fmt(p.bodyweight)}</td>
      <td class="dim">${esc(p.style ?? "—")}</td>
      <td class="num ${metric === "muscle_up" ? "metric" : ""}">${fmt(p.muscle_up)}</td>
      <td class="num ${metric === "pull_up" ? "metric" : ""}">${fmt(p.pull_up)}</td>
      <td class="num ${metric === "dip" ? "metric" : ""}">${fmt(p.dip)}</td>
      <td class="num ${metric === "squat" ? "metric" : ""}">${fmt(p.squat)}</td>
      <td class="num ${metric === "total" ? "metric" : ""}">${fmt(p.total)}</td>
      <td class="num ${metric === "ris" ? "metric" : ""}">${fmt(p.ris)}</td>
      <td class="dim">${esc(p.competition ?? "—")}</td>
      <td class="dim">${fmtDate(p.date)}</td>
    </tr>`).join("")}</tbody>`;

  $("#rankings-table").innerHTML = thead + body;
}

/* ---------- records ---------- */
function renderRecords() {
  const source = $("#r-source").value;
  const gender = $("#r-gender").value;
  const grid = $("#records-grid");
  const mn = t().metric_names;

  if (source === "finalrep") {
    const recs = state.records.finalrep.filter(r => r.gender === gender);
    const byClass = {};
    recs.forEach(r => (byClass[r.class] ??= []).push(r));
    const classes = Object.keys(byClass).sort((a, b) => parseFloat(a.replace("+", "9")) - parseFloat(b.replace("+", "9")));
    grid.innerHTML = classes.map(c => `<div class="record-card">
      <h3>${esc(c)}</h3>
      ${["total", "muscle_up", "pull_up", "dip", "squat"].map(m => {
        const r = byClass[c].find(x => x.movement === m);
        if (!r) return "";
        const ig = r.instagram ? ` <a href="https://instagram.com/${esc(r.instagram.slice(1))}" target="_blank" rel="noopener" class="dim">${esc(r.instagram)}</a>` : "";
        return `<div class="record-row">
          <span class="record-move">${mn[m]}</span>
          <span class="record-holder">${esc(r.athlete)}${ig}</span>
          <span class="record-value">${fmt(r.weight_kg)} kg</span>
        </div>`;
      }).join("")}
    </div>`).join("") || `<p class="loading">${t().no_data}</p>`;
  } else {
    const recs = state.records.computed_osl.filter(r => r.gender === gender);
    const byClass = {};
    recs.forEach(r => (byClass[r.class] ??= []).push(r));
    const classes = Object.keys(byClass).sort((a, b) =>
      a === "all" ? -1 : b === "all" ? 1 :
      parseFloat(a.replace("+", "9")) - parseFloat(b.replace("+", "9")));
    grid.innerHTML = classes.map(c => `<div class="record-card">
      <h3>${c === "all" ? t().all_classes : esc(c)}</h3>
      ${["total", "ris", "muscle_up", "pull_up", "dip", "squat"].map(m => {
        const r = byClass[c].find(x => x.movement === m);
        if (!r) return "";
        return `<div class="record-row">
          <span class="record-move">${mn[m]}</span>
          <span class="record-holder"><span class="athlete-link" data-athlete="${esc(r.athlete_id)}">${flagEmoji(r.country)} ${esc(r.athlete)}</span></span>
          <span class="record-value">${fmt(r.value)}${m === "ris" ? "" : " kg"}</span>
        </div>`;
      }).join("")}
    </div>`).join("") || `<p class="loading">${t().no_data}</p>`;
  }
}

/* ---------- athletes ---------- */
function renderAthletes() {
  const q = $("#a-search").value.trim().toLowerCase();
  const gender = $("#a-gender").value;
  let rows = state.athletes.filter(a =>
    (!gender || a.gender === gender) &&
    (!q || `${a.name} ${a.country}`.toLowerCase().includes(q)));

  const key = state.sort.key || "best.total";
  const get = (a) => key === "name" ? (a.name || "") : key === "n" ? a.n_competitions :
    key === "ris" ? (a.best_ris ?? -1) : (a.best?.[key] ?? -1);
  rows.sort((a, b) => {
    const va = get(a), vb = get(b);
    return (typeof va === "string" ? va.localeCompare(vb) : va - vb) * state.sort.dir;
  });

  const headers = [
    ["name", "col_athlete"], ["n", "col_ncomp"], ["muscle_up", "col_mu"], ["pull_up", "col_pu"],
    ["dip", "col_dip"], ["squat", "col_sq"], ["total", "col_total"], ["ris", "col_best_ris"],
  ];
  $("#athletes-table").innerHTML =
    `<thead><tr>${headers.map(([k, label]) =>
      `<th data-sort="${k}" class="${state.sort.key === k ? "sorted" : ""} ${k === "name" ? "" : "num"}">${t()[label]}</th>`).join("")}</tr></thead>` +
    `<tbody>${rows.map(a => `<tr>
      <td><span class="athlete-link" data-athlete="${esc(a.id)}"><span class="flag">${flagEmoji(a.country)}</span>${esc(a.name)}</span></td>
      <td class="num">${a.n_competitions}</td>
      <td class="num">${fmt(a.best?.muscle_up)}</td>
      <td class="num">${fmt(a.best?.pull_up)}</td>
      <td class="num">${fmt(a.best?.dip)}</td>
      <td class="num">${fmt(a.best?.squat)}</td>
      <td class="num">${fmt(a.best?.total)}</td>
      <td class="num">${fmt(a.best_ris)}</td>
    </tr>`).join("")}</tbody>`;
}

/* ---------- athlete modal ---------- */
